#!/usr/bin/env python3
"""Generate the note index from a small catalog."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def load_catalog():
    groups = json.loads((ROOT / 'docs/catalog.json').read_text(encoding='utf-8'))
    paths, ids = set(), set()
    for group in groups:
        slug = group['id']
        if not re.fullmatch(r'[a-z][a-z-]*', slug) or slug in ids:
            raise ValueError(f'Invalid or repeated category: {slug}')
        ids.add(slug)
        for item in group['items']:
            path = item['path']
            if not re.fullmatch(rf'docs/{slug}/[a-z0-9-]+\.md', path) or path in paths:
                raise ValueError(f'Invalid or repeated note path: {path}')
            if not (ROOT / path).is_file():
                raise ValueError(f'Missing note: {path}')
            paths.add(path)
    supplemental = {'docs/shell/exercises.md'}
    discovered = {str(p.relative_to(ROOT)) for p in (ROOT / 'docs').glob('*/*.md')}
    unlisted = discovered - paths - supplemental
    if unlisted:
        raise ValueError('Notes missing from catalog: ' + ', '.join(sorted(unlisted)))
    return groups


def outputs():
    groups = load_catalog()
    count = sum(len(group['items']) for group in groups)
    lines = ['# 命令目录', '', '[返回首页](../README.md) · [排障路线](troubleshooting.md) · [Shell 练习](shell/exercises.md)', '',
             f'共 {count} 篇命令笔记，按 {len(groups)} 个主题分类。示例以 Linux / GNU 工具 / Bash 为主；按需替换 PID、网卡与文件路径。', '',
             '<!-- Generated by tools/build_index.py; edit docs/catalog.json. -->', '']
    for group in groups:
        lines.extend([f'<a id="{group["id"]}"></a>', '', f'## {group["title"]}', '', '| 笔记 | 用途 |', '| --- | --- |'])
        for item in group['items']:
            path = item['path']
            lines.append(f'| [{item["name"]}]({path.removeprefix("docs/")}) | {item["summary"]} |')
        lines.append('')
    return {'docs/README.md': '\n'.join(lines)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if generated files are stale')
    args = parser.parse_args()
    stale = []
    for relative, content in outputs().items():
        path = ROOT / relative
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != content:
                stale.append(relative)
        else:
            path.write_text(content, encoding='utf-8')
    if stale:
        parser.exit(1, 'Run python3 tools/build_index.py; stale files:\n' + '\n'.join(stale) + '\n')
    print('Note index is up to date.' if args.check else 'Updated note index.')


if __name__ == '__main__':
    main()
